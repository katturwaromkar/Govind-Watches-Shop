function setLanguage(langCode) {
  if (!TRANSLATIONS[langCode]) return;
  localStorage.setItem('govind_lang', langCode);
  document.documentElement.setAttribute('lang', langCode);
  
  const currentLangLabel = document.getElementById('currentLangLabel');
  if (currentLangLabel) {
    const labels = { en: 'English', hi: 'हिंदी', mr: 'मराठी' };
    currentLangLabel.textContent = labels[langCode];
  }
  
  translatePageContent(langCode);
}

function translatePageContent(langCode) {
  const dictionary = TRANSLATIONS[langCode];
  if (!dictionary) return;
  
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (dictionary[key]) {
      if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
        element.placeholder = dictionary[key];
      } else {
        element.textContent = dictionary[key];
      }
    }
  });
}

function toggleLangDropdown() {
  const dropdown = document.getElementById('langDropdown');
  if (dropdown) dropdown.classList.toggle('active');
}

function initI18n() {
  const savedLang = localStorage.getItem('govind_lang') || 'en';
  setLanguage(savedLang);
  
  // Close dropdown on outside click
  document.addEventListener('click', (e) => {
    if (!e.target.closest('.lang-selector')) {
      const dropdown = document.getElementById('langDropdown');
      if (dropdown) dropdown.classList.remove('active');
    }
  });
}

document.addEventListener('DOMContentLoaded', initI18n);
